// Builds tile-sprite.js from public/tiles/*.svg.
// Each tile becomes an SVG <symbol>. The white "st0" fill becomes currentColor,
// so a face is tinted by setting `color` on its <svg>. Everything else keeps
// the default black fill, exactly like the p5 tint in main.js.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const TILE_COUNT = 27;

const symbols = [];
for (let i = 1; i <= TILE_COUNT; i++) {
  const raw = readFileSync(join(root, 'public', 'tiles', `${i}.svg`), 'utf8');
  const inner = raw
    .replace(/<\?xml[^>]*\?>/g, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/<style[\s\S]*?<\/style>/g, '')
    .replace(/class="st0"/g, 'fill="currentColor"')
    .replace(/\sid="[^"]*"/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  symbols.push(`<symbol id="t${i}" viewBox="0 0 90 90">${inner}</symbol>`);
}

const sprite =
  '<svg xmlns="http://www.w3.org/2000/svg" width="0" height="0" aria-hidden="true" ' +
  'style="position:absolute;width:0;height:0;overflow:hidden"><defs>' +
  symbols.join('') +
  '</defs></svg>';

writeFileSync(
  join(root, 'tile-sprite.js'),
  `// Generated by scripts/build-tile-sprite.mjs. Do not edit by hand.\nexport const TILE_COUNT = ${TILE_COUNT};\nexport const TILE_SPRITE = ${JSON.stringify(sprite)};\n`
);
console.log(`Wrote tile-sprite.js (${sprite.length} chars, ${TILE_COUNT} tiles)`);
